import type { FieldsResponse, FieldSnapshot } from "./types"

function field(
  partial: Pick<FieldSnapshot, "id" | "points" | "areaHa"> & Partial<FieldSnapshot>,
): FieldSnapshot {
  const xs = partial.points.map((point) => point[0])
  const zs = partial.points.map((point) => point[1])
  const centerX = xs.reduce((sum, value) => sum + value, 0) / xs.length
  const centerZ = zs.reduce((sum, value) => sum + value, 0) / zs.length
  return {
    centerX,
    centerZ,
    farmId: null,
    farmlandId: null,
    owned: null,
    fruitName: null,
    fruitTitle: null,
    fruitIcon: null,
    iconUrl: null,
    growth: null,
    growthMax: null,
    harvestMin: null,
    harvestMax: null,
    crop: null,
    ground: null,
    weed: null,
    weedFactor: null,
    stones: null,
    spray: null,
    sprayType: null,
    lime: null,
    roller: null,
    plow: null,
    stubble: null,
    water: null,
    scanned: null,
    nitrogen: null,
    nitrogenTarget: null,
    ph: null,
    phTarget: null,
    soil: null,
    soilName: null,
    ...partial,
  }
}

